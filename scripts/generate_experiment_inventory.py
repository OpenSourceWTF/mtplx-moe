#!/usr/bin/env python3
"""Generate the grouped experiment and compatibility settings inventory."""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

DESTINATION = REPO_ROOT / "docs" / "experiments" / "inventory.md"


def _source_locations() -> dict[str, tuple[str, ...]]:
    from mtplx.settings.legacy_env import DIRECT_READ_ALLOWLIST

    locations: dict[str, set[str]] = defaultdict(set)
    for path, name in DIRECT_READ_ALLOWLIST:
        locations[name].add(path)
    return {name: tuple(sorted(paths)) for name, paths in locations.items()}


def _coverage_text() -> tuple[str, str]:
    profiles = (REPO_ROOT / "mtplx" / "profiles.py").read_text(encoding="utf-8")
    tests = "\n".join(
        path.read_text(encoding="utf-8", errors="replace")
        for path in sorted((REPO_ROOT / "tests").glob("test_*.py"))
    )
    return profiles, tests


def _inventory_rows() -> list[dict[str, Any]]:
    from mtplx.experiments.catalog import default_experiment_catalog
    from mtplx.settings.builtins import default_setting_catalog
    from mtplx.settings.legacy_env import INTERNAL_ENV_SPECS

    settings_catalog = default_setting_catalog()
    experiments = default_experiment_catalog().list(active_only=True)
    bundles_by_setting: dict[str, list[str]] = defaultdict(list)
    for recipe in experiments:
        for name in recipe.settings:
            bundles_by_setting[name].append(recipe.id)

    locations = _source_locations()
    profiles_text, tests_text = _coverage_text()
    rows: list[dict[str, Any]] = []

    for spec in settings_catalog.by_name.values():
        env_names = tuple(
            alias.name for alias in spec.aliases if alias.source == "env"
        )
        if not env_names and spec.visibility.value != "experimental" and spec.lifecycle.value != "compatibility":
            continue
        coverage = list(bundles_by_setting.get(spec.name, ()))
        if any(name in profiles_text for name in env_names):
            coverage.append("profile")
        if spec.name in tests_text or any(name in tests_text for name in env_names):
            coverage.append("test")
        source_paths = sorted(
            {path for name in env_names for path in locations.get(name, ())}
        )
        rows.append(
            {
                "domain": spec.domain,
                "name": spec.name,
                "env": env_names,
                "visibility": spec.visibility.value,
                "lifecycle": spec.lifecycle.value,
                "coverage": tuple(coverage),
                "locations": tuple(source_paths),
                "purpose": spec.description or "canonical settings surface",
                "recommendation": (
                    "retain as active control"
                    if bundles_by_setting.get(spec.name)
                    else "retain as catalog setting"
                ),
            }
        )

    for name, spec in INTERNAL_ENV_SPECS.items():
        coverage: list[str] = []
        if name in profiles_text:
            coverage.append("profile")
        if name in tests_text:
            coverage.append("test")
        rows.append(
            {
                "domain": spec.domain,
                "name": name,
                "env": (name,),
                "visibility": spec.visibility,
                "lifecycle": spec.lifecycle,
                "coverage": tuple(coverage),
                "locations": locations.get(name, ()),
                "purpose": spec.classification,
                "recommendation": (
                    "retain as internal"
                    if coverage
                    else "investigate for archive"
                ),
            }
        )
    return sorted(rows, key=lambda row: (row["domain"], row["name"]))


def _cell(values: tuple[str, ...]) -> str:
    return "<br>".join(f"`{value}`" for value in values) if values else "—"


def render_inventory() -> str:
    rows = _inventory_rows()
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        groups[row["domain"]].append(row)
    uncovered = sum(
        row["lifecycle"] == "compatibility" and not row["coverage"]
        for row in rows
    )
    lines = [
        "# Experiment and Compatibility Settings Inventory",
        "",
        "<!-- Generated by scripts/generate_experiment_inventory.py. -->",
        "",
        f"Total classified rows: {len(rows)}. Compatibility rows without active bundle/profile/test coverage: {uncovered}.",
        "",
        "Active bundles are data-only controls; this inventory does not authorize hardware execution.",
        "",
    ]
    for domain in sorted(groups):
        lines.extend(
            [
                f"## {domain}",
                "",
                "| Setting | Environment alias | Visibility | Lifecycle | Coverage | Source locations | Apparent purpose | Recommendation |",
                "|---|---|---|---|---|---|---|---|",
            ]
        )
        for row in groups[domain]:
            lines.append(
                "| "
                + " | ".join(
                    (
                        f"`{row['name']}`",
                        _cell(row["env"]),
                        row["visibility"],
                        row["lifecycle"],
                        _cell(row["coverage"]),
                        _cell(row["locations"]),
                        str(row["purpose"]).replace("|", "\\|"),
                        row["recommendation"],
                    )
                )
                + " |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = render_inventory()
    if args.write:
        DESTINATION.parent.mkdir(parents=True, exist_ok=True)
        DESTINATION.write_text(expected, encoding="utf-8")
        print(f"wrote {DESTINATION}")
        return 0
    if not DESTINATION.exists() or DESTINATION.read_text(encoding="utf-8") != expected:
        print(f"error: stale experiment inventory: {DESTINATION}")
        return 1
    print(f"experiment inventory ok: {len(_inventory_rows())} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
